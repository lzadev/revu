// Interface text lives here so every message is in one place. revu speaks English only.
export function makeT() {
  return (key, vars = {}) => {
    const v = dict[key] ?? key;
    return typeof v === 'string' ? v.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '') : v;
  };
}
